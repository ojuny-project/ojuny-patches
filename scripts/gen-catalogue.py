#!/usr/bin/env python3
"""Generate CATALOGUE.md from every patch-*/metadata.md file."""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "CATALOGUE.md"
FIELDS = ("name", "id", "description", "dependencies", "version")
FIELD_RE = re.compile(r"^(name|id|description|dependencies|version):[ \t]*(.*)$")


def parse_metadata(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = FIELD_RE.match(line)
        if match:
            values[match.group(1)] = match.group(2).strip()
    return values


def escape_cell(value: str) -> str:
    return value.replace("|", "\\|").strip()


def main() -> int:
    entries = []
    errors = []

    for path in sorted(ROOT.glob("patch-*/metadata.md")):
        metadata = parse_metadata(path)
        missing = [field for field in FIELDS if field not in metadata]
        if missing:
            errors.append(f"{path.relative_to(ROOT)}: missing {', '.join(missing)}")
            continue

        description = metadata["description"]
        if not description:
            errors.append(f"{path.relative_to(ROOT)}: empty description")
            continue
        if len(description.split()) < 2:
            errors.append(f"{path.relative_to(ROOT)}: one-word description")
            continue

        entries.append(metadata)

    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    entries.sort(key=lambda entry: entry["id"])

    lines = [
        "# Patch catalogue",
        "",
        "Generated by `scripts/gen-catalogue.py`. Do not edit by hand.",
        "",
        f"Total patches: {len(entries)}",
        "",
        "| ID | Name | Version | Description |",
        "| --- | --- | --- | --- |",
    ]
    for entry in entries:
        lines.append(
            "| {id} | {name} | {version} | {description} |".format(
                id=escape_cell(entry["id"]),
                name=escape_cell(entry["name"]),
                version=escape_cell(entry["version"]),
                description=escape_cell(entry["description"]),
            )
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(entries)} patches")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
